func scaffoldAppTS(module, entity, action string) string {
	return fmt.Sprintf(`/**
 * Forma TypeScript sidecar app — generated by `+"`forma generate node-app`"+`.
 *
 * Registers business-logic handlers and starts the App listener on
 * FORMA_APP_SOCKET (unix:///tmp/forma-app.sock by default).
 *
 * forma dev spawns this process as a child, calls POST /invoke/... for
 * actions with impl: { type: sidecar }, and forwards ctx.* primitive
 * calls back to the engine over FORMA_SIDECAR_SOCKET.
 */

import { App } from "@forma/lib-forma";
import { register%sHandler } from "./handlers/%s";

const app = new App();
register%sHandler(app);

app.run().then((server) => {
  const addr = server.address();
  process.stderr.write("[%s] ready on " + JSON.stringify(addr) + "\n");
});
`, pascalCase(module)+pascalCase(entity), action, pascalCase(module)+pascalCase(entity), module)
}

func scaffoldHandlerTS(module, entity, action string) string {
	handlerID := fmt.Sprintf("%s.%s.%s", module, entity, action)
	handlerType := pascalCase(module) + pascalCase(entity)

	return fmt.Sprintf(`/**
 * %s handler — example sidecar action.
 *
 * This runs in a Node.js child process, communicating with the forma engine
 * over a unix domain socket. Use ctx.entity() for atomic entity operations.
 *
 * Register this handler in src/app.ts.
 */

import { ActionResult, App } from "@forma/lib-forma";

export function register%sHandler(app: App): void {
  app.handle("%s", async (inv, ctx) => {
    process.stderr.write("[%s] invoked: resource_id=" + inv.resourceId + "\n");

    // Example: use ctx.entity() for atomic field operations.
    //   await ctx
    //     .entity()
    //     .named("module/entity")
    //     .decrement(inv.resourceId, "stock", 1, inv.tenantId);

    // Return action result with optional state transition.
    return new ActionResult(
      { processed: true, at: new Date().toISOString() },
      "processed",
    );
  });
}
`, pascalCase(module)+pascalCase(entity)+pascalCase(action), handlerType, handlerID, handlerID)
}

