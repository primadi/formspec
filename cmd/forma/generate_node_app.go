// Command `forma generate node-app` scaffolds a TypeScript sidecar app for a
// new Forma project. It creates the complete boilerplate: package.json,
// tsconfig, entrypoint with App listener, example handler, and a
// forma-sidecar.yaml that enables `forma dev --runtime node` with tsx watch.
//
// Usage:
//
//	forma generate node-app [--dir ./my-app] [--module my-module] [--entity my-entity]
//
// Flags:
//
//	--dir        Target directory (default: ./app)
//	--module     Module name for example handler (default: "myapp")
//	--entity     Entity name for example handler (default: "myentity")
//	--action     Action name for example handler (default: "process")
package main

import (
	_ "embed"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// runGenerateNodeApp scaffolds a new Node.js TypeScript sidecar app.
func runGenerateNodeApp(args []string) {
	fs := flag.NewFlagSet("generate node-app", flag.ExitOnError)
	dir := fs.String("dir", "./app", "Target directory for the scaffolded app")
	moduleName := fs.String("module", "myapp", "Module name for the example handler")
	entityName := fs.String("entity", "myentity", "Entity name for the example handler")
	actionName := fs.String("action", "process", "Action name for the example handler")
	fs.Usage = func() {
		fmt.Fprintf(os.Stderr, "Usage: forma generate node-app [flags]\n\n")
		fmt.Fprintf(os.Stderr, "Scaffold a TypeScript sidecar app for a Forma project.\n\n")
		fmt.Fprintf(os.Stderr, "Flags:\n")
		fs.PrintDefaults()
	}
	fs.Parse(args)

	absDir, err := filepath.Abs(*dir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}

	// Check target directory doesn't already exist
	if _, err := os.Stat(absDir); err == nil {
		fmt.Fprintf(os.Stderr, "Error: target %s already exists\n", absDir)
		os.Exit(1)
	}

	mod := strings.ToLower(*moduleName)
	ent := strings.ToLower(*entityName)
	act := strings.ToLower(*actionName)

	// Create directory structure
	dirs := []string{
		filepath.Join(absDir, "src", "handlers"),
	}
	for _, d := range dirs {
		if err := os.MkdirAll(d, 0755); err != nil {
			fmt.Fprintf(os.Stderr, "Error: create %s: %v\n", d, err)
			os.Exit(1)
		}
	}

	// Write files
	files := map[string]string{
		"package.json":  scaffoldPackageJSON(),
		"tsconfig.json": scaffoldTSConfig(),
		"src/app.ts":    scaffoldAppTS(mod, ent, act),
		filepath.Join("src", "handlers", act+".ts"): scaffoldHandlerTS(mod, ent, act),
		"forma-sidecar.yaml":                        scaffoldFormaSidecarYAML(),
		".gitignore":                                scaffoldGitignore(),
	}

	for relPath, content := range files {
		fullPath := filepath.Join(absDir, relPath)
		if err := os.MkdirAll(filepath.Dir(fullPath), 0755); err != nil {
			fmt.Fprintf(os.Stderr, "Error: create dir for %s: %v\n", relPath, err)
			os.Exit(1)
		}
		if err := os.WriteFile(fullPath, []byte(content), 0644); err != nil {
			fmt.Fprintf(os.Stderr, "Error: write %s: %v\n", fullPath, err)
			os.Exit(1)
		}
	}

	fmt.Printf("✅ Scaffolded Node.js sidecar app in %s\n\n", absDir)
	fmt.Printf("Next steps:\n")
	fmt.Printf("  cd %s\n", absDir)
	fmt.Printf("  npm install\n")
	fmt.Printf("  cd .. && forma dev\n")
	fmt.Printf("\nEdit src/handlers/%s.ts to implement your business logic.\n", act)
	fmt.Printf("The entrypoint %s.%s.%s will be served via sidecar.\n", mod, ent, act)
}

