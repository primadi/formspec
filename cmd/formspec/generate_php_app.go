// Command `formspec generate php-app` scaffolds a PHP sidecar app.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

func runGeneratePHPApp(args []string) {
	fs := flag.NewFlagSet("generate php-app", flag.ExitOnError)
	dir := fs.String("dir", "./app", "Target directory for the scaffolded app")
	moduleName := fs.String("module", "myapp", "Module name for the example handler")
	entityName := fs.String("entity", "myentity", "Entity name for the example handler")
	actionName := fs.String("action", "process", "Action name for the example handler")
	fs.Usage = func() {
		fmt.Fprintf(os.Stderr, "Usage: formspec generate php-app [flags]\n\n")
		fmt.Fprintf(os.Stderr, "Scaffold a PHP sidecar app for a FormSpec project.\n\n")
		fmt.Fprintf(os.Stderr, "Flags:\n")
		fs.PrintDefaults()
	}
	fs.Parse(args)

	absDir, err := filepath.Abs(*dir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}
	if _, err := os.Stat(absDir); err == nil {
		fmt.Fprintf(os.Stderr, "Error: target %s already exists\n", absDir)
		os.Exit(1)
	}

	mod := strings.ToLower(*moduleName)
	ent := strings.ToLower(*entityName)
	act := strings.ToLower(*actionName)

	files := map[string]string{
		"composer.json":  scaffoldPHPComposer(),
		"app.php":        scaffoldPHPApp(mod, ent, act),
		"formspec-app.yaml": scaffoldPHPAppYAML(),
		".gitignore":     scaffoldPHPGitignore(),
	}

	for relPath, content := range files {
		fullPath := filepath.Join(absDir, relPath)
		if err := os.MkdirAll(filepath.Dir(fullPath), 0755); err != nil {
			fmt.Fprintf(os.Stderr, "Error: create dir for %s: %v\n", relPath, err)
			os.Exit(1)
		}
		if err := os.WriteFile(fullPath, []byte(content), 0644); err != nil {
			fmt.Fprintf(os.Stderr, "Error: write %s: %v\n", fullPath, err)
			os.Exit(1)
		}
	}

	fmt.Printf("✅ Scaffolded PHP sidecar app in %s\n\n", absDir)
	fmt.Printf("Next steps:\n")
	fmt.Printf("  cd %s\n", absDir)
	fmt.Printf("  composer install\n")
	fmt.Printf("  cd .. && formspec dev\n")
}

func scaffoldPHPComposer() string {
	return `{
    "name": "myapp/formspec-sidecar",
    "description": "FormSpec PHP sidecar app",
    "type": "project",
    "require": {
        "php": ">=8.1",
        "formspec/lib-formspec": "@dev"
    },
    "autoload": {
        "psr-4": {
            "App\\": "src/"
        }
    },
    "repositories": [
        {
            "type": "path",
            "url": "../../sdk/php"
        }
    ]
}
`
}

func scaffoldPHPApp(module, entity, action string) string {
	handlerID := fmt.Sprintf("%s.%s.%s", module, entity, action)
	return fmt.Sprintf(`<?php
/**
 * FormSpec PHP sidecar app — generated by `+"`formspec generate php-app`"+`.
 *
 * Registers business-logic handlers and starts the App listener.
 */

require __DIR__ . '/vendor/autoload.php';

use FormSpec\App;
use FormSpec\ActionResult;

$app = new App();

$app->handle('%s', function ($inv, $ctx) {
    fwrite(STDERR, "[%s] invoked: resource_id=" . $inv->resourceId . "\n");
    return new ActionResult(
        ['processed' => true, 'at' => date(DATE_ATOM)],
        'processed'
    );
});

$app->run();
`, handlerID, handlerID)
}

func scaffoldPHPAppYAML() string {
	return `# ── FormSpec App Config — PHP Sidecar App ──
#
# Generated by ` + "`formspec generate php-app`" + `.

spec: spec
dsn: sqlite:.formspec/data.db
runtime: php
app-dir: app
app-entrypoint: app.php
dev: true
`
}

func scaffoldPHPGitignore() string {
	return `vendor/
.formspec/
*.db
*.db-shm
*.db-wal
/tmp/formspec-*.sock
`
}
